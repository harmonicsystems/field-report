#!/usr/bin/env node
/*
 * make-runsheet.mjs
 *
 * Generates runsheet.html — a local, gitignored page of prefilled-query
 * links for running a manual audit cycle. One row per query in
 * schema/audit/queries.json; one link per surface. Tapping a link opens
 * the surface with the query ready: the human still runs each query,
 * reads the answer, and judges it. This is navigation, not collection —
 * the audit's "manual by design" posture is unchanged.
 *
 * The output is intentionally NOT published (the repo root deploys to
 * GitHub Pages); it's session tooling, regenerated whenever the query
 * set changes.
 *
 * Usage: node tools/make-runsheet.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(fileURLToPath(import.meta.url), '../..');
const OUT = resolve(REPO_ROOT, 'runsheet.html');

const esc = (s) => String(s ?? '')
  .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;');

// Prefill targets. Google Maps uses the documented Maps URLs scheme
// (developers.google.com/maps/documentation/urls) — the one sanctioned
// way to open a search in the app without any API key.
const LINKS = [
  { key: 'aio',     label: 'Google',  url: q => `https://www.google.com/search?q=${encodeURIComponent(q)}` },
  { key: 'maps',    label: 'Maps',    url: q => `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(q)}` },
  { key: 'claude',  label: 'Claude',  url: q => `https://claude.ai/new?q=${encodeURIComponent(q)}` },
  { key: 'chatgpt', label: 'ChatGPT', url: q => `https://chatgpt.com/?q=${encodeURIComponent(q)}` },
];

const queriesDoc = JSON.parse(await readFile(resolve(REPO_ROOT, 'schema/audit/queries.json'), 'utf-8'));
const queries = queriesDoc.queries || [];

const rows = queries.map(q => `    <tr>
      <td class="q"><span class="qid">${esc(q.id)}</span>${esc(q.query)}</td>
      ${LINKS.map(l => `<td class="s"><a href="${esc(l.url(q.query))}" target="_blank" rel="noopener">${l.label}</a></td>`).join('\n      ')}
    </tr>`).join('\n');

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Audit run sheet (local) — ${esc(queriesDoc.queries?.length ?? 0)} queries</title>
<style>
  :root { --bg:#f4efe4; --ink:#1a1614; --soft:#3b342e; --rule:#c9c0ae; --accent:#a63d2a;
    --mono:ui-monospace,monospace; --serif:Georgia,serif; }
  body { margin:0; padding:32px 24px 80px; background:var(--bg); color:var(--ink); font-family:var(--serif); }
  .wrap { max-width: 860px; margin: 0 auto; }
  h1 { font-weight:400; font-size:26px; margin:0 0 6px; }
  .note { font-style:italic; color:var(--soft); font-size:14px; margin:0 0 24px; max-width:640px; line-height:1.5; }
  table { width:100%; border-collapse:collapse; font-size:14px; }
  td { padding:9px 8px; border-bottom:1px solid var(--rule); vertical-align:baseline; }
  td.q { line-height:1.4; }
  .qid { display:block; font-family:var(--mono); font-size:10px; color:var(--soft); letter-spacing:0.04em; }
  td.s { white-space:nowrap; }
  td.s a { font-family:var(--mono); font-size:12px; color:var(--accent); text-decoration:none;
    border:1px solid var(--rule); padding:3px 9px; display:inline-block; }
  td.s a:hover { border-color:var(--accent); }
  .foot { margin-top:20px; font-family:var(--mono); font-size:11px; color:var(--soft); line-height:1.6; }
</style>
</head>
<body>
<div class="wrap">
  <h1>Audit run sheet — cycle in progress</h1>
  <p class="note">Local tooling, not published. Each link opens the surface with the query prefilled;
  you run it, read it, and paste what came back (with any cited links) into the session.
  No AI answer shown? Say so and move on. AI Overviews trigger inconsistently — that's data.</p>
  <table>
${rows}
  </table>
  <p class="foot">Generated by tools/make-runsheet.mjs from schema/audit/queries.json (${esc(queriesDoc.status || 'final')} set).<br>
  Paste format per observation: &nbsp;<b>q-id / surface</b> → answer text → links cited.</p>
</div>
</body>
</html>
`;

await writeFile(OUT, html);
console.log(`[make-runsheet] wrote ${OUT}  (${queries.length} queries × ${LINKS.length} surfaces)`);
